#!/usr/bin/env python3
"""Turn os/boot/uboot/wisp-trial.txt into the C header the bootloader build compiles in (include/configs/wisp-env.h): two environment variables,
  wisp_trial    the script (comment lines dropped, the other lines joined with a space), and
  boot_extlinux the distro boot's own variable, redefined to run wisp_trial before it starts extlinux (U-Boot's default environment is read in order, so the later definition wins).
usage: make_env.py wisp-trial.txt OUT.h        The original definition of boot_extlinux is `sysboot ${devtype} ${devnum}:${distro_bootpart} any ${scriptaddr} ${prefix}${boot_syslinux_conf}`
(include/config_distro_bootcmd.h); install_env.py checks the tree still has exactly that before it builds. No double quote or backslash may appear in the script (C string)."""
import sys
from pathlib import Path

BOOT_EXTLINUX = 'run wisp_trial; sysboot ${devtype} ${devnum}:${distro_bootpart} any ${scriptaddr} ${prefix}${boot_syslinux_conf}'


def script(text):
    lines = [l.strip() for l in text.splitlines() if l.strip() and not l.lstrip().startswith('#')]
    s = ' '.join(lines)
    if '"' in s or '\\' in s: raise SystemExit('make_env: the script must not contain a double quote or a backslash')
    return s


def header(text):
    return ('/* Generated by os/boot/uboot/make_env.py from wisp-trial.txt: do not edit. */\n#ifndef WISP_ENV_H\n#define WISP_ENV_H\n'
            '#define WISP_ENV \\\n\t"wisp_trial=%s\\0" \\\n\t"boot_extlinux=%s\\0"\n#endif\n' % (script(text), BOOT_EXTLINUX))


if __name__ == '__main__':
    if len(sys.argv) != 3: raise SystemExit(__doc__)
    Path(sys.argv[2]).write_text(header(Path(sys.argv[1]).read_text()))
