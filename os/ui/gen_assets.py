#!/usr/bin/env python3
"""Generate wisp-ui-assets.h for programs that cannot use SDL (the boot splash): anti-aliased glyph atlases of the WispOS UI typeface and the badge image,
rendered from the SAME files the first-time setup screen loads at run time, at the sizes in os/ui/wisp-ui.h. The header is a build product (about 200 KB of
data, not committed). usage: gen_assets.py --fonts DIR --badge PNG --out wisp-ui-assets.h
DIR holds LiberationSans-Bold.ttf and LiberationSans-Regular.ttf (the image's /usr/share/fonts/liberation, or any host copy for a test).
Atlas: ASCII 32..126; per glyph a width, height, left bearing and top (from the text line's top), an advance, and an offset into one 8-bit alpha array.
The badge, twice: scaled to WISP_UI_BADGE_H (the identity column of the setup screens) and to WISP_UI_BOOT_BADGE_H (the centred boot screen), BGRA with straight alpha (the order a 32-bpp framebuffer wants)."""
import argparse, re, sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent


def token(name):
    m = re.search(r'#define\s+%s\s+(\S+)' % name, (HERE / 'wisp-ui.h').read_text())
    if not m: sys.exit('token %s not found in wisp-ui.h' % name)
    return int(m.group(1), 0)


def atlas(path, size, name, out):
    font = ImageFont.truetype(str(path), size, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    pad = size
    data, glyphs = bytearray(), []
    for cp in range(32, 127):
        ch = chr(cp)
        img = Image.new('L', (size * 3, size * 3), 0)
        ImageDraw.Draw(img).text((pad, pad + ascent), ch, font=font, fill=255, anchor='ls')
        bbox = img.getbbox()
        adv = int(round(font.getlength(ch)))
        if bbox is None:
            glyphs.append((0, 0, 0, 0, adv, len(data))); continue
        x0, y0, x1, y1 = bbox
        glyph = img.crop(bbox)
        glyphs.append((x1 - x0, y1 - y0, x0 - pad, y0 - pad, adv, len(data)))
        data += glyph.tobytes()
    out.append('static const unsigned char %s_alpha[%d] = {%s};' % (name, len(data), ','.join(str(b) for b in data)))
    out.append('static const struct wisp_glyph %s_glyphs[95] = {%s};' % (name, ','.join('{%d,%d,%d,%d,%d,%d}' % g for g in glyphs)))
    out.append('static const struct wisp_font %s = {%d, %d, %s_glyphs, %s_alpha};' % (name, ascent, ascent + descent, name, name))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fonts', required=True); ap.add_argument('--badge', required=True); ap.add_argument('--out', required=True)
    a = ap.parse_args()
    fonts = Path(a.fonts)
    bold, regular = fonts / 'LiberationSans-Bold.ttf', fonts / 'LiberationSans-Regular.ttf'
    for f in (bold, regular):
        if not f.is_file(): sys.exit('missing font file: %s' % f)
    out = ['/* Generated by os/ui/gen_assets.py: glyph atlases (Liberation Sans) and the badge. Do not edit; do not commit. */',
           '#ifndef WISPOS_UI_ASSETS_H', '#define WISPOS_UI_ASSETS_H',
           'struct wisp_glyph { unsigned char w, h; signed char left, top; unsigned char adv; unsigned int off; };',
           'struct wisp_font { int ascent, height; const struct wisp_glyph *glyphs; const unsigned char *alpha; };']
    atlas(bold, token('WISP_UI_SIZE_TITLE'), 'font_title', out)
    atlas(regular, token('WISP_UI_SIZE_BODY'), 'font_body', out)
    atlas(regular, token('WISP_UI_SIZE_SMALL'), 'font_small', out)
    atlas(regular, token('WISP_UI_SIZE_TINY'), 'font_tiny', out)
    src = Image.open(a.badge).convert('RGBA')
    for suffix, tok in (('', 'WISP_UI_BADGE_H'), ('_boot', 'WISP_UI_BOOT_BADGE_H')):
        h = token(tok); w = max(1, round(src.width * h / src.height))
        img = src.resize((w, h), Image.LANCZOS)
        px = bytearray()
        for r, g, b, al in img.getdata(): px += bytes((b, g, r, al))
        out.append('#define WISP_BADGE%s_W %d' % (suffix.upper(), w)); out.append('#define WISP_BADGE%s_H %d' % (suffix.upper(), h))
        out.append('static const unsigned char wisp_badge%s_bgra[%d] = {%s};' % (suffix, len(px), ','.join(str(v) for v in px)))
    out.append('#endif')
    Path(a.out).write_text('\n'.join(out) + '\n')
    print('wrote %s (%d bytes)' % (a.out, Path(a.out).stat().st_size))


if __name__ == '__main__':
    main()
